/**
 * Bundles the browser half into the one file the DSH module loader expects.
 *
 * The loader serves `lib/client.js` as a plain script, so the bundle is wrapped
 * in `window.__ModuleLoader__.load({ id, factory })`. Everything the host
 * already provides (React, the client packages) stays external and is resolved
 * through the `require` the loader passes into the factory.
 */

import { mkdirSync, writeFileSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

import { build } from 'esbuild';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const PLUGIN_ID = 'dsh-autonomy';

const result = await build({
  entryPoints: [resolve(root, 'src/client/index.ts')],
  bundle: true,
  format: 'cjs',
  platform: 'browser',
  target: ['es2022'],
  write: false,
  sourcemap: false,
  logLevel: 'warning',
  external: ['react', 'react-dom', 'react-dom/client', '@deepseek-ai/*'],
});

const code = result.outputFiles[0]?.text ?? '';
if (code === '') {
  console.error('build-client: esbuild produced no output');
  process.exit(1);
}

const body = code
  .split('\n')
  .map((line) => (line === '' ? '' : `    ${line}`))
  .join('\n');

const wrapped = `/* generated by scripts/build-client.mjs — do not edit */
window.__ModuleLoader__.load({
  id: ${JSON.stringify(PLUGIN_ID)},
  factory: (require) => {
    const module = { exports: {} };
    const exports = module.exports;
${body}
    return module.exports;
  },
});
`;

mkdirSync(resolve(root, 'lib'), { recursive: true });
writeFileSync(resolve(root, 'lib/client.js'), wrapped, 'utf8');
console.log(`build-client: lib/client.js ${wrapped.length} bytes`);
